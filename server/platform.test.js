import { test } from 'node:test';
import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import { fileURLToPath } from 'node:url';
import { MongoMemoryServer } from 'mongodb-memory-server';
import { createApp } from './app.js';
import User from './models/User.js';
import Project from './models/Project.js';
import Task from './models/Task.js';
import TimeEntry from './models/TimeEntry.js';

test('MongoDB authentication, private workspaces, and persistent timers', { timeout: 900000 }, async () => {
  const mongo = await MongoMemoryServer.create({ binary: { downloadDir: fileURLToPath(new URL('../node_modules/.cache/mongodb/', import.meta.url)) } });
  let server;
  try {
    await mongoose.connect(mongo.getUri());
    await Promise.all([User.init(), Project.init(), Task.init(), TimeEntry.init()]);
    process.env.SESSION_SECRET = 'test-only-secret-with-more-than-32-characters';
    process.env.APP_ORIGIN = 'http://127.0.0.1:5173';
    server = createApp().listen(0, '127.0.0.1');
    await new Promise(resolve => server.once('listening', resolve));
    const base = `http://127.0.0.1:${server.address().port}/api/`;
    function client() {
      let cookie = '';
      return async (path, body, method = 'POST', origin = process.env.APP_ORIGIN) => {
        const response = await fetch(base + path, { method: body === undefined ? 'GET' : method, headers: { Origin: origin, 'Content-Type': 'application/json', Cookie: cookie }, body: body === undefined ? undefined : JSON.stringify(body) });
        if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
        return { status: response.status, body: await response.json() };
      };
    }
    const alice = client(), bob = client(), stranger = client();
    assert.equal((await stranger('data')).status, 401);
    assert.equal((await stranger('auth/register', { name: 'Invalid', email: 'bad', password: 'short' })).status, 400);
    assert.equal((await alice('auth/register', { name: 'Alice', email: 'alice@example.com', password: 'password123' })).status, 201);
    assert.equal((await alice('auth/me')).body.user.name, 'Alice');
    assert.equal((await alice('auth/me')).body.user.passwordHash, undefined);
    assert.equal((await alice('auth/register', { name: 'Alice', email: 'alice@example.com', password: 'password123' })).status, 409);
    const stored = await User.findOne({ email: 'alice@example.com' }).select('+passwordHash');
    assert.notEqual(stored.passwordHash, 'password123');
    assert.equal((await bob('auth/register', { name: 'Bob', email: 'bob@example.com', password: 'password123' })).status, 201);
    const created = await alice('projects', { name: 'Private project' });
    assert.equal(created.status, 200);
    const projectId = created.body.projects[0].id;
    assert.equal((await bob('data')).body.projects.length, 0);
    assert.equal((await bob('tasks', { title: 'Intrusion', projectId })).status, 404);
    const task = (await alice('tasks', { title: 'Build app', projectId })).body.tasks[0];
    const manual = { taskId: task.id, start: '2025-01-10T09:00:00.000Z', end: '2025-01-10T10:30:00.000Z' };
    assert.equal((await bob('entries', manual)).status, 404);
    assert.equal((await alice('entries', { ...manual, end: manual.start })).status, 400);
    assert.equal((await alice('entries', { ...manual, start: 'invalid' })).status, 400);
    assert.equal((await alice('entries', { ...manual, end: '2099-01-10T10:30:00.000Z' })).status, 400);
    const recorded = await alice('entries', manual);
    assert.equal(recorded.status, 200);
    assert.equal(recorded.body.entries.length, 1);
    assert.equal(recorded.body.entries[0].end - recorded.body.entries[0].start, 90 * 60000);
    assert.equal(recorded.body.active, null);
    const entryId = recorded.body.entries[0].id;
    assert.equal((await bob('entries/' + entryId, manual, 'PATCH')).status, 404);
    assert.equal((await alice('entries/' + entryId, { start: manual.start, end: manual.start }, 'PATCH')).status, 400);
    const changedTime = await alice('entries/' + entryId, { start: manual.start, end: '2025-01-10T10:00:00.000Z' }, 'PATCH');
    assert.equal(changedTime.status, 200);
    assert.equal(changedTime.body.entries[0].end - changedTime.body.entries[0].start, 60 * 60000);
    assert.equal((await alice('entries/' + entryId, { start: manual.start, end: manual.end }, 'PATCH')).status, 200);
    await alice('entries', { ...manual, start: '2025-01-10T12:00:00.000Z', end: '2025-01-10T13:00:00.000Z' });
    assert.equal((await alice('entries/' + entryId, { start: manual.start, end: '2025-01-10T12:30:00.000Z' }, 'PATCH')).status, 409);
    await TimeEntry.deleteMany({ task: task.id, start: new Date('2025-01-10T12:00:00.000Z') });
    assert.equal((await alice('entries', manual)).status, 409);
    assert.equal((await alice('entries', { ...manual, start: '2025-01-10T10:00:00.000Z', end: '2025-01-10T11:00:00.000Z' })).status, 409);
    assert.equal((await bob('data')).body.entries.length, 0);
    await TimeEntry.deleteMany({ task: task.id });
    assert.equal(task.status, 'todo');
    assert.equal(task.priority, 'medium');
    for (const values of [{ status: 'invalid' }, { priority: 'urgent' }, { dueDate: '2026-02-30' }, { dueDate: 'tomorrow' }]) {
      assert.equal((await alice('tasks/' + task.id, values, 'PATCH')).status, 400);
      assert.equal((await alice('tasks', { title: 'Invalid', projectId, ...values })).status, 400);
    }
    const scheduled = await alice('tasks/' + task.id, { status: 'in-progress', priority: 'high', dueDate: '2026-12-31' }, 'PATCH');
    assert.equal(scheduled.body.tasks[0].status, 'in-progress');
    assert.equal(scheduled.body.tasks[0].priority, 'high');
    assert.equal(scheduled.body.tasks[0].dueDate.slice(0, 10), '2026-12-31');
    assert.equal((await alice('tasks/' + task.id, { status: 'done' }, 'PATCH')).body.tasks[0].done, true);
    const cleared = await alice('tasks/' + task.id, { status: 'todo', priority: 'low', dueDate: '' }, 'PATCH');
    assert.equal(cleared.body.tasks[0].done, false);
    assert.equal(cleared.body.tasks[0].dueDate, null);
    assert.equal((await bob('projects/' + projectId, { name: 'Stolen' }, 'PATCH')).status, 404);
    assert.equal((await bob('projects/' + projectId, { archived: true }, 'PATCH')).status, 404);
    assert.equal((await alice('projects/' + projectId, { name: ' ' }, 'PATCH')).status, 400);
    assert.equal((await alice('projects/' + projectId, { archived: 'true' }, 'PATCH')).status, 400);
    const edited = await alice('projects/' + projectId, { name: 'Updated project', description: 'New description' }, 'PATCH');
    assert.equal(edited.body.projects[0].name, 'Updated project');
    assert.equal(edited.body.projects[0].description, 'New description');
    assert.equal((await alice('projects/' + projectId, { archived: true }, 'PATCH')).body.projects[0].archived, true);
    assert.equal((await alice('tasks', { title: 'Blocked', projectId })).status, 404);
    assert.equal((await alice('entries', manual)).status, 409);
    assert.equal((await alice('timer', { taskId: task.id })).status, 409);
    assert.equal((await alice('data')).body.tasks.length, 1);
    assert.equal((await alice('projects/' + projectId, { archived: false }, 'PATCH')).body.projects[0].archived, false);
    assert.equal((await bob('tasks/' + task.id, {}, 'PATCH')).status, 404);
    assert.equal((await bob('tasks/' + task.id, {}, 'DELETE')).status, 404);
    assert.equal((await alice('tasks/' + task.id, { title: ' ' }, 'PATCH')).status, 400);
    assert.equal((await alice('tasks/' + task.id, { description: 'x'.repeat(5001) }, 'PATCH')).status, 400);
    const updatedTask = await alice('tasks/' + task.id, { title: 'Updated task', description: 'Task notes' }, 'PATCH');
    assert.equal(updatedTask.body.tasks[0].title, 'Updated task');
    assert.equal(updatedTask.body.tasks[0].description, 'Task notes');
    assert.equal(updatedTask.body.tasks[0].done, false);
    assert.equal((await bob('timer', { taskId: task.id })).status, 404);
    const bobId = (await bob('auth/me')).body.user.id;
    assert.equal((await alice('projects/' + projectId + '/members', { email: 'unknown@example.com' })).status, 400);
    const shared = await alice('projects/' + projectId + '/members', { email: 'bob@example.com' });
    assert.equal(shared.status, 200);
    assert.equal(shared.body.projects[0].teammates.length, 2);
    await alice('projects/' + projectId + '/members', { email: 'bob@example.com' });
    assert.equal((await bob('data')).body.projects[0].role, 'member');
    assert.equal((await bob('data')).body.projects[0].teammates.length, 2);
    assert.equal((await bob('projects/' + projectId, { archived: true }, 'PATCH')).status, 404);
    assert.equal((await bob('projects/' + projectId + '/members', { email: 'alice@example.com' })).status, 404);
    const assigned = await bob('tasks/' + task.id, { assignee: bobId }, 'PATCH');
    assert.equal(assigned.status, 200);
    assert.equal(assigned.body.tasks[0].assignee, bobId);
    assert.equal((await bob('tasks/' + task.id, { assignee: '000000000000000000000001' }, 'PATCH')).status, 400);
    const memberTask = await bob('tasks', { title: 'Member task', projectId });
    assert.equal(memberTask.status, 200);
    const memberTaskId = memberTask.body.tasks.find(t => t.title === 'Member task').id;
    assert.equal((await alice('tasks/' + memberTaskId, {}, 'DELETE')).status, 200);
    assert.equal((await bob('timer', { taskId: task.id })).status, 200);
    assert.equal((await alice('data')).body.active, null);
    assert.equal((await alice('projects/' + projectId, { archived: true }, 'PATCH')).status, 409);
    assert.equal((await alice('tasks/' + task.id, {}, 'DELETE')).status, 409);
    assert.equal((await alice('projects/' + projectId + '/members/' + bobId, {}, 'DELETE')).status, 409);
    await bob('timer', {});
    assert.equal((await alice('data')).body.entries.length, 0);
    assert.equal((await alice('projects/' + projectId + '/members/' + bobId, {}, 'DELETE')).status, 200);
    assert.equal((await bob('data')).body.projects.length, 0);
    assert.equal((await bob('data')).body.entries.length, 1);
    assert.equal((await bob('tasks/' + task.id, { title: 'Denied' }, 'PATCH')).status, 404);
    assert.equal((await alice('data')).body.tasks[0].assignee, null);
    await TimeEntry.deleteMany({ owner: bobId });
    const starts = await Promise.all([alice('timer', { taskId: task.id }), alice('timer', { taskId: task.id })]);
    assert.deepEqual(starts.map(r => r.status).sort(), [200, 409]);
    assert.equal(await TimeEntry.countDocuments({ end: null }), 1);
    assert.equal((await alice('tasks/' + task.id, {}, 'DELETE')).status, 409);
    assert.equal((await alice('tasks/' + task.id, { title: 'Blocked' }, 'PATCH')).status, 409);
    assert.equal((await alice('projects/' + projectId, { archived: true }, 'PATCH')).status, 409);
    assert.equal((await alice('tasks/' + task.id, {}, 'PATCH')).status, 409);
    assert.equal((await alice('data')).body.active.taskId, task.id);
    assert.equal((await alice('timer', {})).body.entries.length, 1);
    const archived = await alice('projects/' + projectId, { archived: true }, 'PATCH');
    assert.equal(archived.body.entries.length, 1);
    assert.equal(archived.body.tasks.length, 1);
    assert.equal(archived.body.projects[0].archived, true);
    await alice('projects/' + projectId, { archived: false }, 'PATCH');
    assert.equal((await alice('timer', {})).body.entries.length, 1);
    assert.equal((await alice('tasks/' + task.id, {}, 'PATCH')).body.tasks[0].done, true);
    assert.equal((await alice('projects', { name: 'Blocked' }, 'POST', 'https://other.example')).status, 403);
    assert.equal((await alice('auth/logout', {})).status, 200);
    assert.equal((await alice('data')).status, 401);
    assert.equal((await alice('auth/login', { email: 'alice@example.com', password: 'wrongpassword' })).status, 401);
    assert.equal((await alice('auth/login', { email: 'alice@example.com', password: 'password123' })).status, 200);
    assert.equal((await alice('data')).body.entries.length, 1);
    const deleted = await alice('tasks/' + task.id, {}, 'DELETE');
    assert.equal(deleted.status, 200);
    assert.equal(deleted.body.tasks.length, 0);
    assert.equal(deleted.body.entries.length, 1);
    assert.equal(deleted.body.entries[0].taskTitle, 'Updated task');
    assert.equal((await alice('tasks/' + task.id, {}, 'DELETE')).status, 404);
    await mongoose.connection.db.collection('sessions').deleteMany({});
    assert.equal((await alice('data')).status, 401);
    assert.equal((await alice('auth/profile', { name: 'No access' }, 'PATCH')).status, 401);
    await alice('auth/login', { email: 'alice@example.com', password: 'password123' });
    assert.equal((await alice('auth/profile', { name: ' ' }, 'PATCH')).status, 400);
    const profile = await alice('auth/profile', { name: 'Alice Updated', email: 'ignored@example.com' }, 'PATCH');
    assert.equal(profile.body.user.name, 'Alice Updated');
    assert.equal(profile.body.user.email, 'alice@example.com');
    assert.equal((await bob('auth/me')).status, 401);
    const another = client();
    await another('auth/login', { email: 'alice@example.com', password: 'password123' });
    assert.equal((await alice('auth/password', { currentPassword: 'wrong', newPassword: 'newpassword123' }, 'PATCH')).status, 400);
    assert.equal((await alice('auth/password', { currentPassword: 'password123', newPassword: 'short' }, 'PATCH')).status, 400);
    assert.equal((await alice('auth/password', { currentPassword: 'password123', newPassword: 'newpassword123' }, 'PATCH')).status, 200);
    assert.equal((await alice('auth/me')).status, 200);
    assert.equal((await another('auth/me')).status, 401);
    await alice('auth/logout', {});
    assert.equal((await alice('auth/login', { email: 'alice@example.com', password: 'password123' })).status, 401);
    assert.equal((await alice('auth/login', { email: 'alice@example.com', password: 'newpassword123' })).status, 200);
  } finally {
    if (server) await new Promise(resolve => server.close(resolve));
    await mongoose.disconnect();
    await mongo.stop();
  }
});
